  String conflictFieldPathLabel(List<String> path) {
    const profileTables = {'人物關係', '組織', '擁有物品', '狀態', '阻礙事件'};
    return [
      for (var i = 0; i < path.length; i++)
        if (i == 0 ||
            (i == path.length - 1 &&
                path.length > 2 &&
                profileTables.contains(path.first)))
          legacyLabel(path[i])
        else
          path[i],
    ].join(' > ');
  }

  String characterTypeLabel(String type) => switch (type) {
    'protagonist' => uiProtagonist,
    'majorSupporting' => uiMajorSupportingCharacter,
    'minorSupporting' => characterMinorSupporting,
    'majorAntagonist' => uiMainAntagonist,
    'minorAntagonist' => uiSecondaryAntagonist,
    'other' => uiOther,
    _ => type,
  };

  String revisionFieldLabel(Iterable<String> path) => path
      .map((part) => legacyLabel(RevisionFieldRegistry.labelFor([part])))
      .join(' / ');
